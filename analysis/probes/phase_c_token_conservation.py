# --------------------------------------------------------------------------------------------------------------- utils
def md5_fold(s):
    return int(hashlib.md5(str(s).encode()).hexdigest(), 16) % 2


def cq(values, sids, q):
    return stats.cluster_quantile(values, sids, q)


def desc(v):
    return stats.describe(v)


def qtab(values, sids, qs=(0.5, 0.9, 0.99)):
    v = np.asarray(values, float)
    if len(v) == 0:
        return {"n": 0}
    out = {"n": int(len(v)), "n_sessions": int(len(set(sids)))}
    for q in qs:
        r = cq(v, sids, q)
        out[f"p{round(q * 100, 1):g}"] = {"value": r["value"], "lo": r["lo"], "hi": r["hi"]}
    return out


def crate(num, den, sids):
    """session-clustered rate: sum per session first."""
    d = pd.DataFrame({"s": sids, "n": np.asarray(num, float), "d": np.asarray(den, float)}).groupby("s").sum()
    return stats.cluster_rate(d["n"].values, d["d"].values)


