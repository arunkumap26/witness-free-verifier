"""Phase C lens: token conservation between consecutive API calls (Phase B split).

Question. Between two consecutive API calls of one conversation thread, the provider-reported prompt size grows by the
tokens of what was appended in between: the previous response (text, tool-call args, thinking) and the model-visible
inputs (tool results, user / system text). The log records both the usage numbers and the appended text. How tightly do
they agree, what breaks the agreement, and how large a change to ONE logged tool result would stand out above the
honest residual at a 1% false-positive rate?

Reads only IR caches analysis/cache/<corpus>_B.parquet (swechat, cc_local, aiv_cc, aiv_cu) plus
analysis/cache/swechat_population.parquet (format per session). No text leaves this script: only lengths/counts of
substrings are computed (cc_local is private; outputs are aggregates; its MCP tool names are collapsed to 'mcp__*' as in
its build report). Writes RAW COUNTS ONLY to
analysis/out/phase_c/token_conservation.json. Interpretation: analysis/notes/token_conservation.md.

Run:  PYTHONIOENCODING=utf-8 python -m analysis.probes.phase_c_token_conservation
Env:  TC_PAIRS_CACHE=<dir>  optional scratch dir to cache the extracted pair table between runs (never under data/).

Definitions (fixed in PREREG below before any residual was computed):
  unit         'fmt' = corpus x log format: swechat:claude_code, swechat:codex, swechat:opencode, swechat:gemini,
               cc_local:claude_code, aiv_cc:claude_code, aiv_cu:anthropic, aiv_cu:gemini.
  thread       one conversation context: main thread, or one subagent (agent_id / parent_call_id) within a session.
  API call     one usage per (session_id, api_msg_id) (USAGE DEDUPE rule, lib/ir.py); usage_out = max over its rows.
  context C    Anthropic-style usage (claude_code formats, opencode, aiv_cu anthropic): input + cache_read + cache_create.
               OpenAI/Gemini-style usage (codex, gemini, aiv_cu gemini): input (already includes cached tokens).
  generated    events of kind assistant/call belonging to the call: same api_msg_id; Codex (no per-item id): the
               assistant/call events between the previous usage row and this call's usage row.
  start_k      smallest seq of any event of call k (Codex: of its generated events, else its usage row).
  window k     events with start_k < seq < start_{k+1} in the thread that are not generated by call k: the inputs
               appended before call k+1 (results, user, system) plus meta markers (compaction etc.).
  dC           C_{k+1} - C_k for consecutive calls k, k+1 of one thread.
"""
