def parse_extra(ex):
    if not isinstance(ex, str) or not ex:
        return {}
    try:
        d = json.loads(ex)
    except Exception:
        return {}
    if not isinstance(d, dict):
        return {}
    out = {k: d.get(k) for k in EXTRA_KEYS if k in d}
    ud = d.get("usage_detail")
    if isinstance(ud, dict):
        ptd = ud.get("promptTokensDetails") or {}
        if isinstance(ptd, dict):
            out["p_text"] = ptd.get("TEXT")
            out["p_image"] = ptd.get("IMAGE")
        out["thoughts_tokens"] = ud.get("thoughtsTokenCount")
    return out


def load_corpus(corpus):
    """IR cache -> event frame with text-derived lengths/counts only (text dropped)."""
    path = os.path.join(CACHE, f"{corpus}_B.parquet")
    f = pq.ParquetFile(path)
    cols = ["session_id", "stratum", "seq", "kind", "tool", "tool_raw", "api_msg_id", "model", "is_subagent", "agent_id",
            "parent_call_id", "usage_in", "usage_out", "usage_cache_read", "usage_cache_create", "native_error", "extra"]
    frames = []
    for rg in range(f.num_row_groups):
        t = f.read_row_group(rg, columns=cols + ["text", "args", "stderr"])
        txt, args, se = t["text"], t["args"], t["stderr"]

        def ln(a):
            return pc.fill_null(pc.utf8_length(a), 0).to_numpy(zero_copy_only=False)

        def cnt(a, pat):
            return pc.fill_null(pc.count_substring(a, pat), 0).to_numpy(zero_copy_only=False)

        feat = {
            "tlen": ln(txt), "tbytes": pc.fill_null(pc.binary_length(txt), 0).to_numpy(zero_copy_only=False),
            "alen": ln(args), "slen": ln(se), "tnull": pc.is_null(txt).to_numpy(zero_copy_only=False),
            "n_img": sum(cnt(txt, p) for p in IMG_PATS) + sum(cnt(args, p) for p in IMG_PATS),
            "n_red": cnt(txt, "REDACTED") + cnt(args, "REDACTED"),
            "persisted": pc.fill_null(pc.starts_with(txt, "<persisted-output>"), False).to_numpy(zero_copy_only=False),
            "continued": pc.fill_null(pc.starts_with(txt, "This session is being continued"), False).to_numpy(zero_copy_only=False),
            "n_nl": cnt(txt, "\n"),
        }
        df = t.select(cols).to_pandas()
        for k, v in feat.items():
            df[k] = v
        frames.append(df)
        del t
    ev = pd.concat(frames, ignore_index=True)
    ex = ev["extra"].map(parse_extra)
    exdf = pd.DataFrame(list(ex.values), index=ev.index)
    ev = pd.concat([ev.drop(columns=["extra"]), exdf], axis=1)
    return ev


def fmt_of(corpus, ev):
    if corpus == "swechat":
        pop = pd.read_parquet(os.path.join(CACHE, "swechat_population.parquet"), columns=["session_id", "format"])
        m = dict(zip(pop.session_id, pop.format))
        return ev["session_id"].map(lambda s: "swechat:" + str(m.get(s)))
    if corpus == "aiv_cu":
        return ev["stratum"].map(lambda s: "aiv_cu:gemini" if str(s).startswith("gemini") else
                                 ("aiv_cu:anthropic" if str(s).startswith("anthropic") else "aiv_cu:other"))
    return pd.Series([f"{corpus}:claude_code"] * len(ev), index=ev.index)


