def design(P, model):
    F = P.F.values
    nF = 1 - F
    cols = {}
    if model == "M_hyb":
        cols = {"res_chars": P.res_chars, "res_nl": P.res_nl, "res_nonascii": P.res_nonascii, "n_results": P.res_n,
                "res_stderr": P.res_stderr_m, "sys_chars": P.sys_chars, "n_system": P.sys_n,
                "F_out": F * P.out_k, "F_reason": F * P.reason_tok_k, "F": F,
                "nF_text": nF * P.gen_text_chars, "nF_args": nF * P.gen_args_chars, "nF_think": nF * P.think,
                "nF_calls": nF * P.n_calls}
    elif model == "M_chars":
        cols = {"res_chars": P.res_chars, "sys_chars": P.sys_chars, "text": P.gen_text_chars, "args": P.gen_args_chars,
                "think": P.think, "n_results": P.res_n, "n_system": P.sys_n}
    elif model == "M_out":
        cols = {"res_chars": P.res_chars, "sys_chars": P.sys_chars, "n_results": P.res_n, "n_system": P.sys_n}
    names = list(cols) + ["intercept"]
    A = np.column_stack([np.asarray(v, float) for v in cols.values()] + [np.ones(len(P))])
    return A, names


def target(P, model, ycol="dC"):
    y = P[ycol].values.astype(float)
    if model == "M_out":
        y = y - P.out_k.values
    return y


MIN_NONZERO = 30


def huber(A, y, iters=50):
    w = np.ones(len(y))
    keep = (A != 0).sum(0) >= MIN_NONZERO
    keep[-1] = True  # intercept
    b = np.zeros(A.shape[1])
    for _ in range(iters):
        sw = np.sqrt(w)
        bk, *_ = np.linalg.lstsq(A[:, keep] * sw[:, None], y * sw, rcond=None)
        b = np.zeros(A.shape[1])
        b[keep] = bk
        r = y - A @ b
        s = 1.4826 * np.median(np.abs(r - np.median(r)))
        c = 1.345 * max(s, 1e-9)
        wn = np.where(np.abs(r) <= c, 1.0, c / np.maximum(np.abs(r), 1e-12))
        done = np.max(np.abs(wn - w)) < 1e-6
        w = wn
        if done:
            break
    return b, w


def crossfit(P, model, ycol="dC"):
    """Out-of-fold residuals (fit on the other fold). Returns (r_oof, coef_by_fold, full coef, full weights, names, A, y)."""
    A, names = design(P, model)
    y = target(P, model, ycol)
    r = np.full(len(y), np.nan)
    coefs = {}
    fold = P.fold.values
    for f in (0, 1):
        tr, te = fold != f, fold == f
        if tr.sum() < 30 or te.sum() == 0:
            continue
        b, _ = huber(A[tr], y[tr])
        r[te] = y[te] - A[te] @ b
        coefs[f] = b
    bfull, wfull = huber(A, y)
    return r, coefs, bfull, wfull, names, A, y


def boot_coef(A, y, w, sids, names, which, n_boot=stats.N_BOOT, seed=SEED):
    """Session bootstrap of weighted LS with the full fit's Huber weights held fixed. Returns {name: (lo, hi)}."""
    keep = (A != 0).sum(0) >= MIN_NONZERO
    keep[-1] = True
    Ak = A[:, keep]
    nk = [n for n, k in zip(names, keep) if k]
    uniq, inv = np.unique(sids, return_inverse=True)
    S, p = len(uniq), Ak.shape[1]
    XtX = np.zeros((S, p, p))
    Xty = np.zeros((S, p))
    Aw = Ak * w[:, None]
    np.add.at(XtX, inv, Aw[:, :, None] * Ak[:, None, :])
    np.add.at(Xty, inv, Aw * y[:, None])
    rng = np.random.default_rng(seed)
    out = {n: [] for n in which if n in nk}
    for _ in range(n_boot):
        cnt = np.bincount(rng.integers(0, S, S), minlength=S).astype(float)
        M = np.tensordot(cnt, XtX, 1)
        v = cnt @ Xty
        b = np.linalg.lstsq(M, v, rcond=None)[0]
        for n in out:
            out[n].append(b[nk.index(n)])
    return {n: (float(np.quantile(v, 0.025)), float(np.quantile(v, 0.975))) for n, v in out.items() if v}


def coef_dict(b, names):
    return {n: float(v) for n, v in zip(names, b)}


def eff_rate(P, coef, names):
    c = dict(zip(names, coef))
    br = c.get("res_chars", 0.0)
    rc = P.res_chars.values.astype(float)
    with np.errstate(divide="ignore", invalid="ignore"):
        nl = np.where(rc > 0, P.res_nl.values / np.maximum(rc, 1), 0.0)
        na = np.where(rc > 0, P.res_nonascii.values / np.maximum(rc, 1), 0.0)
    return br + c.get("res_nl", 0.0) * nl + c.get("res_nonascii", 0.0) * na


# ----------------------------------------------------------------------------------------------------------- detection
GRID = np.array([10 ** (i / 20) for i in range(0, 121)])
REPORT_DELTAS = [100, 300, 1000, 3000, 10000, 30000, 100000]
WIN_BINS = [0, 1e2, 1e3, 1e4, 1e5, np.inf]
RES_BINS = PREREG["bins_result_chars"]


def thresholds(absr, logged_chars):
    T = float(np.quantile(absr, 0.99))
    tb = {}
    bi = np.digitize(logged_chars, WIN_BINS[1:-1])
    for b in range(len(WIN_BINS) - 1):
        m = bi == b
        tb[b] = float(np.quantile(absr[m], 0.99)) if m.sum() >= 100 else T
    return T, tb


def detect(r, shift, logged, T, tb, mode):
    if mode == "asym":
        rs = r - shift
        return (rs < tb["lo"]) | (rs > tb["hi"])
    rr = np.abs(r - shift)
    if mode == "abs":
        return rr > T
    bi = np.digitize(logged, WIN_BINS[1:-1])
    thr = np.array([tb[b] for b in range(len(WIN_BINS) - 1)])[bi]
    return rr > thr


def flags_for(r, rate, win, fold, delta, Tf, mode):
    fl = np.zeros(len(r), bool)
    for f in (0, 1):
        m = fold == f
        if m.any():
            d = delta[m] if np.ndim(delta) else delta
            fl[m] = detect(r[m], rate[m] * d, win[m] + d, Tf[f][0], Tf[f][1], mode)
    return fl


def detection(C, r, rate, sids):
    """C: clean pairs (same order as r); rate: per-pair effective tokens/char from the model of the pair's fold."""
    fold = C.fold.values
    win = (C.res_chars + C.sys_chars).values.astype(float)
    resmax = C.res_max.values.astype(float)
    ok = ~np.isnan(r) & ~np.isnan(rate)
    out = {"thresholds": {}, "realized_fpr": {}, "power": {}, "by_result_size": {}}
    Tf, Ta = {}, {}
    for f in (0, 1):
        other = ok & (fold != f)
        if other.sum() < 100:
            return {"skipped": "fewer than 100 out-of-fold residuals in a fold"}
        T, tb = thresholds(np.abs(r[other]), win[other])
        Tf[f] = (T, tb)
        Ta[f] = (T, {"lo": float(np.quantile(r[other], 0.005)), "hi": float(np.quantile(r[other], 0.995))})
        out["thresholds"][f"applied_to_fold{f}"] = {
            "T_abs": T, "T_bin": {f"[{WIN_BINS[b]:g},{WIN_BINS[b + 1]:g})": v for b, v in tb.items()},
            "T_asym": Ta[f][1], "from_n_pairs": int(other.sum())}
    TT = {"abs": Tf, "bin": Tf, "asym": Ta}
    for mode in ("abs", "bin", "asym"):
        fl = flags_for(r[ok], rate[ok], win[ok], fold[ok], 0.0, TT[mode], mode)
        out["realized_fpr"][mode] = crate(fl.astype(float), np.ones(ok.sum()), sids[ok])
    elig = ok & (C.res_n.values > 0)
    out["eligible_pairs_with_result"] = int(elig.sum())
    for mode in ("abs", "bin", "asym"):
        res = {}
        for sign in (1, -1):
            key = "longer" if sign > 0 else "shorter"
            res[key] = {"min_delta_power_0.5": None, "min_delta_power_0.9": None, "at": {}}
            for d in GRID:
                e = elig & (resmax >= d) if sign < 0 else elig
                if e.sum() < 30:
                    break
                fl = flags_for(r[e], rate[e], win[e], fold[e], sign * d, TT[mode], mode)
                pw = float(fl.mean())
                for tgt in ("0.5", "0.9"):
                    k2 = f"min_delta_power_{tgt}"
                    if res[key][k2] is None and pw >= float(tgt):
                        res[key][k2] = {"delta_chars": float(d), "power": pw, "n_pairs": int(e.sum())}
            for D in REPORT_DELTAS:
                e = elig & (resmax >= D) if sign < 0 else elig
                if e.sum() < 30:
                    res[key]["at"][str(D)] = {"n_pairs": int(e.sum())}
                    continue
                fl = flags_for(r[e], rate[e], win[e], fold[e], sign * float(D), TT[mode], mode)
                cr = crate(fl.astype(float), np.ones(len(fl)), sids[e])
                res[key]["at"][str(D)] = {"power": cr["rate"], "lo": cr["lo"], "hi": cr["hi"], "n_pairs": int(e.sum()),
                                          "n_sessions": cr["n_sessions"]}
        out["power"][mode] = res
    for b in range(len(RES_BINS) - 1):
        lo, hi = RES_BINS[b], RES_BINS[b + 1]
        sel = elig & (resmax >= lo) & (resmax < hi)
        key = f"[{lo:g},{hi:g})"
        if sel.sum() < 30:
            out["by_result_size"][key] = {"n_pairs": int(sel.sum())}
            continue
        entry = {"n_pairs": int(sel.sum()), "n_sessions": int(len(set(sids[sel]))),
                 "result_chars_median": float(np.median(resmax[sel]))}
        for mode in ("abs", "bin", "asym"):
            for sign in (1, -1):
                best = {"0.5": None, "0.9": None}
                for d in GRID:
                    e = sel & (resmax >= d) if sign < 0 else sel
                    if e.sum() < 30:
                        break
                    fl = flags_for(r[e], rate[e], win[e], fold[e], sign * d, TT[mode], mode)
                    pw = float(fl.mean())
                    for tgt in ("0.5", "0.9"):
                        if best[tgt] is None and pw >= float(tgt):
                            best[tgt] = {"delta_chars": float(d), "power": pw, "n_pairs": int(e.sum())}
                    if best["0.9"] is not None:
                        break
                entry[f"{mode}_{'longer' if sign > 0 else 'shorter'}_min_delta"] = best
            rel = {}
            for frac in (-1.0, -0.5, 0.5, 1.0, 3.0):
                delta = frac * resmax[sel]
                fl = flags_for(r[sel], rate[sel], win[sel], fold[sel], delta, TT[mode], mode)
                cr = crate(fl.astype(float), np.ones(len(fl)), sids[sel])
                rel[f"{frac:+g}"] = {"power": cr["rate"], "lo": cr["lo"], "hi": cr["hi"]}
            entry[f"{mode}_relative_change_power"] = rel
        out["by_result_size"][key] = entry
    return out


