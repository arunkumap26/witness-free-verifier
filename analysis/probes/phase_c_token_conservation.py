    out = {"prereg": PREREG, "post_hoc": POST_HOC, "build_counters": counters, "fmt": {}}
    for fmt in FMTS:
        if only and fmt not in only.split(","):
            continue
        print("fmt", fmt, round(time.time() - t0, 1), file=sys.stderr)
